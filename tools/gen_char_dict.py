TAG_RE = re.compile(r"^[a-z0-9_][a-z0-9_\.\-\':\(\)]*$")


def call_grok(prompt, min_count):
    body = {
        "model": LLM.get("model", "grok-4"),
        "messages": [
            {"role": "system", "content": SYSTEM},
            {"role": "user", "content": prompt + f"。保底至少 {min_count} 个，越多越好。"},
        ],
        "temperature": 0,
        "max_tokens": 16000,
    }
    req = urllib.request.Request(
        f"{LLM['base_url'].rstrip('/')}/chat/completions",
        data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json",
                 "Authorization": f"Bearer {LLM['api_key'].strip()}"},
        method="POST")
    with urllib.request.urlopen(req, timeout=240) as r:
        return json.loads(r.read())["choices"][0]["message"]["content"]


def parse_entries(text):
    text = text.strip()
    text = re.sub(r"^```(json)?\s*", "", text)
    text = re.sub(r"\s*```$", "", text)
    i, j = text.find("["), text.rfind("]")
    arr = None
    if i >= 0 and j > i:
        try:
            arr = json.loads(text[i:j + 1])
        except json.JSONDecodeError:
            arr = None
    if arr is None:
        # 截断兜底：逐个抓完整对象
        arr = []
        for m in re.finditer(r"\{[^{}]*\}", text):
            try:
                arr.append(json.loads(m.group(0)))
            except json.JSONDecodeError:
                continue
    out = []
    for e in arr:
        if not isinstance(e, dict):
            continue
        tag = str(e.get("tag", "")).strip().lower().replace(" ", "_")
        names = [str(n).strip() for n in (e.get("names") or []) if str(n).strip()]
        if tag and names and TAG_RE.match(tag) and len(tag) < 80:
            out.append((tag, names))
    return out


def completed_count():
    try:
        return sum(1 for l in open(LOG_PATH, encoding="utf-8") if '"gen"' in l)
    except FileNotFoundError:
        return 0


def main():
    d = json.loads(DICT_PATH.read_text(encoding="utf-8"))
    es = d["entries"]
    existing = {e["tag"] for e in es}
    log = open(LOG_PATH, "a", encoding="utf-8")
    total_added = 0
    skip = completed_count()
    for idx, (series, prompt, minimum) in enumerate(CALLS, 1):
        if idx <= skip:
            continue
        best = []
        for attempt in range(3):
            try:
                raw = call_grok(prompt, minimum)
                best = parse_entries(raw)
                if best:
                    break
            except Exception as e:
                log.write(json.dumps({"series": series, "error": str(e)[:120]}, ensure_ascii=False) + "\n")
                log.flush()
                time.sleep(20)
        added = 0
        for tag, names in best:
            if tag in existing:
                continue
            es.append({"tag": tag, "series": series, "names": names})
            existing.add(tag)
            added += 1
        total_added += added
        DICT_PATH.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding="utf-8")
        log.write(json.dumps({"i": idx, "series": series, "gen": len(best), "added": added,
                              "total": len(es)}, ensure_ascii=False) + "\n")
        log.flush()
        print(f"[{idx}/{len(CALLS)}] {series}: 生成{len(best)} 新增{added} | 累计{len(es)}", flush=True)
        time.sleep(2)
    log.close()
    print(f"全部完成：新增 {total_added}，总计 {len(es)}", flush=True)


if __name__ == "__main__":
    main()
